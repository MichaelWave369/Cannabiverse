import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {parseMGF,screenMSMS,mgfPrecursorRows,H2O_LOSS,CO2_LOSS} from '../app/discovery/msms-core.mjs';
import {analyzeFeatures} from '../app/discovery/lab-core.mjs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const synthetic=read('data/discovery/demo-msms-synthetic.mgf');
assert.match(synthetic,/SYNTHETIC MGF test fixture only/);
const spectra=parseMGF(synthetic);
assert.equal(spectra.length,4);
assert.deepEqual(spectra.map(s=>s.polarity),['positive','positive','negative','positive']);
assert.ok(spectra[0].precursor_mz>300);
assert.equal(spectra[0].peaks.length,8);
assert.equal(spectra[2].adduct,'[M-H]-');
assert.equal(spectra[2].retention_seconds,180);
const out=screenMSMS(spectra,{ppm_tolerance:20,source_reference:'SYNTHETIC_DATA_ONLY'});
assert.equal(out.schema,'cannabiverse-msms-screen-v0.2');
assert.equal(out.evidence_level,'FRAGMENT_PATTERN_ONLY_NO_IDENTITY');
assert.equal(out.source_reference_unverified,'SYNTHETIC_DATA_ONLY');
assert.equal(out.scans.length,4);
assert.equal(out.scans[0].fragment_count_screen,'FRAGMENT_COUNT_SCREEN_PASS');
assert.equal(out.scans[3].fragment_count_screen,'LOW_FRAGMENT_INFORMATION');
assert.ok(out.loss_matches.some(x=>x.spectrum_index===1&&x.loss_label==='H₂O mass difference'&&Math.abs(x.observed_loss_da-H2O_LOSS)<1e-7));
assert.ok(out.loss_matches.some(x=>x.spectrum_index===1&&x.loss_label==='CO₂ mass difference'&&Math.abs(x.observed_loss_da-CO2_LOSS)<1e-7));
assert.ok(out.loss_matches.every(x=>x.interpretation.includes('NOT cannabinoid-specific')));
assert.equal(JSON.stringify(out),JSON.stringify(screenMSMS(spectra,{ppm_tolerance:20,source_reference:'SYNTHETIC_DATA_ONLY'})));
const features=mgfPrecursorRows(spectra);
const precursor=analyzeFeatures(features);
assert.equal(precursor.features.length,4);
assert.equal(precursor.features.filter(x=>x.screening_status==='INSUFFICIENT_QC').length,4);
assert.ok(precursor.pairs.length>0);
assert.ok(precursor.pairs.every(x=>x.review_status==='QC_REVIEW'));
const simple='BEGIN IONS\nTITLE=A\nPEPMASS=300.1 100\nCHARGE=1+\nMSLEVEL=2\n70.1 100\nEND IONS\n';
assert.equal(parseMGF(simple).length,1);
assert.throws(()=>parseMGF(simple.replace('CHARGE=1+','CHARGE=2+')),/Unsupported or missing singly charged CHARGE/);
assert.throws(()=>parseMGF(simple.replace('MSLEVEL=2','MSLEVEL=1')),/Only MSLEVEL=2/);
assert.throws(()=>parseMGF(simple.replace('PEPMASS=300.1 100','')),/PEPMASS missing/);
assert.throws(()=>parseMGF(simple.replace('70.1 100','70.1 BAD')),/Invalid MS\/MS peak/);
assert.throws(()=>parseMGF(simple.replace('END IONS','')),/Unclosed BEGIN IONS/);
assert.throws(()=>parseMGF(simple.replace('IONMODE','IONMODE').replace('CHARGE=1+','CHARGE=1+\nIONMODE=Negative')),/conflict/);
assert.throws(()=>parseMGF(simple.replace('70.1 100','70.1 0')),/All-zero intensities/);
assert.throws(()=>parseMGF('x'.repeat(2_000_001)),/2 MB/);
assert.throws(()=>screenMSMS(spectra,{ppm_tolerance:500}),/Invalid MS\/MS ppm tolerance/);
const html=read('app/discovery/index.html'),ui=read('app/discovery/lab-ui.mjs');
for(const id of ['mgf-file','mgf-text','run-msms','msms-scans','msms-losses','source-ref','export-msms'])assert.ok(html.includes('id="'+id+'"'),'Missing UI: '+id);
assert.match(ui,/parseMGF\(/);
assert.match(html,/Not a cannabinoid identification system/);
console.log('PASS v0.2 MGF: 4 synthetic spectra, charge/polarity validation, H2O-CO2 non-diagnostic mass patterns, negative adducts, provenance and fail-closed imports');

import assert from 'node:assert/strict';
import {readFileSync,mkdtempSync,existsSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createHash} from 'node:crypto';
import {createAudit,runCLI} from './audit-discovery-mgf.mjs';
const bytes=readFileSync(new URL('../data/discovery/demo-msms-synthetic.mgf',import.meta.url));
const report=createAudit({bytes,role:'sample',dataset_id:'MSV000093886',input_name:'synthetic-demo.mgf'});
const expected=createHash('sha256').update(bytes).digest('hex');
assert.equal(report.schema,'cannabiverse-local-msms-provenance-audit-v0.3');
assert.equal(report.provenance.sha256_bytes,expected);
assert.equal(report.provenance.byte_length,bytes.length);
assert.equal(report.provenance.dataset_id_user_asserted,'MSV000093886');
assert.equal(report.provenance.registered_dataset.id,'MSV000093886');
assert.equal(report.provenance.registered_dataset.access_status,'PARTIAL_PUBLIC');
assert.equal(report.provenance.source_attribution_status,'NOT_AUTHENTICATED');
assert.equal(report.provenance.has_verified_blank_or_reference_standard,false);
assert.equal(report.msms_screen.scans.length,4);
assert.equal(report.precursor_pattern_screen.features.length,4);
assert.ok(report.precursor_pattern_screen.features.every(x=>x.screening_status==='INSUFFICIENT_QC'));
assert.equal(report.evidence_level,'EXPERIMENTAL_FORMAT_OBSERVATIONS_ONLY_NO_COMPOUND_IDENTITY');
assert.ok(report.caveats.some(x=>x.includes('does not authenticate')));
assert.equal(JSON.stringify(createAudit({bytes,role:'sample',dataset_id:'MSV000093886',input_name:'synthetic-demo.mgf'})),JSON.stringify(report),'Deterministic audit');
const unregistered=createAudit({bytes,role:'unknown',dataset_id:'UNREGISTERED'});
assert.equal(unregistered.provenance.registered_dataset,null);
assert.equal(unregistered.provenance.role_user_asserted,'unknown');
const blank=createAudit({bytes,role:'blank'});
assert.equal(blank.provenance.has_verified_blank_or_reference_standard,false,'User asserts blank, but no independent verification');
assert.throws(()=>createAudit({bytes,role:'researcher_confirmed'}),/Unknown sample role/);
assert.throws(()=>createAudit({bytes,dataset_id:'MSV-NOT-REAL'}),/Unknown dataset registry ID/);
assert.throws(()=>createAudit({bytes,declared_polarity:'positive'}),/Declared polarity conflicts/);
assert.throws(()=>createAudit({bytes:Buffer.alloc(2_000_001)}),/2,000,000 bytes/);
const temp=mkdtempSync(join(tmpdir(),'cv-audit-'));
try{
  const output=join(temp,'audit.json');
  const result=runCLI(['--input',new URL('../data/discovery/demo-msms-synthetic.mgf',import.meta.url).pathname,
    '--role','sample','--dataset','MSV000093886','--output',output]);
  assert.ok(existsSync(output));
  assert.equal(result.scan_count,4);
  const cliReport=JSON.parse(readFileSync(output,'utf8'));
  assert.equal(cliReport.provenance.sha256_bytes,expected);
  assert.equal(cliReport.provenance.source_attribution_status,'NOT_AUTHENTICATED');
  assert.throws(()=>runCLI(['--input','example.mgf']),/Required: --role/);
}finally{rmSync(temp,{recursive:true,force:true});}
const registry=JSON.parse(readFileSync(new URL('../data/discovery/public-data-sources-v1.json',import.meta.url),'utf8'));
assert.equal(registry.dataset_id,'cannabiverse-public-msms-source-registry');
assert.equal(registry.sources.length,1);
assert.equal(registry.sources[0].id,'MSV000093886');
assert.equal(registry.sources[0].license,'CC0-1.0');
assert.equal(registry.sources[0].associated_workflow.task_id,'cdd0ffbbe4d241c5b4e8437825b7bce2');
assert.ok(registry.editorial_notice.includes('not an assertion'));
console.log('PASS Discovery v0.3 provenance: SHA256 local bytes, known public source, CLI run, role/polarity guards and no authenticated-attribution claims');
